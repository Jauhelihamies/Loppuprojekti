using System.Collections.Generic;
using UnityEngine;

[RequireComponent(typeof(AudioSource))]
public class RecorderGuy : MonoBehaviour
{
    [System.Serializable]
    public struct CustomSound
    {
        public string soundName;
        public AudioClip clip;
        [Range(0f, 1f)] public float volume;
    }

    [Header("Sound List")]
    [SerializeField] private CustomSound[] soundList;

    [Header("3D Sound Settings")]
    [Tooltip("0 is fully 2D, 1 is fully 3D")]
    [Range(0f, 1f)][SerializeField] private float spatialBlend = 1f;
    [SerializeField] private float min3DDistance = 1f;
    [SerializeField] private float max3DDistance = 50f;
    [SerializeField] private AudioRolloffMode rolloffMode = AudioRolloffMode.Logarithmic;

    [Header("Head Look Settings")]
    [Tooltip("Auto-finds 'mixamorig:Head' if left empty.")]
    [SerializeField] private Transform headBone;
    [Tooltip("Drag the Player transform here. If left empty, it will look for the 'Player' tag.")]
    [SerializeField] private Transform player;
    [SerializeField] private float lookDistance = 5f;
    [SerializeField] private float headTurnSpeed = 5f;
    [SerializeField] private float maxLookAngle = 75f;
    [SerializeField] private Vector3 headRotationOffset = Vector3.zero;
    [SerializeField] private Vector3 playerTargetOffset = new Vector3(0f, 1.5f, 0f);

    [Header("Continuous Laugh Shake")]
    [Tooltip("Auto-fills with Mixamo chest and shoulder bones on Start.")]
    [SerializeField] private List<Transform> laughingParts = new List<Transform>();
    [SerializeField] private float shakeSpeed = 25f;
    [SerializeField] private Vector3 shakeRotationAmount = new Vector3(2.5f, 1f, 2f);
    [SerializeField] private Vector3 shakePositionAmount = new Vector3(0f, 0.004f, 0f);

    [Header("Ragdoll Settings")]
    [Tooltip("Check this box in the Inspector during Play Mode to trigger the ragdoll.")]
    [SerializeField] private bool activateRagdoll = false;
    [Tooltip("Stops the laughing audio when ragdoll activates.")]
    [SerializeField] private bool stopAudioOnRagdoll = true;

    private AudioSource audioSource;
    private Animator animator;
    private Collider mainCollider;
    private Rigidbody mainRigidbody;

    private Rigidbody[] ragdollRigidbodies;
    private Collider[] ragdollColliders;

    private Quaternion currentHeadRotation;
    private float shakeSeed;
    private bool isRagdollActive = false;

    void Start()
    {
        audioSource = GetComponent<AudioSource>();
        animator = GetComponent<Animator>();
        mainCollider = GetComponent<Collider>();
        mainRigidbody = GetComponent<Rigidbody>();

        shakeSeed = Random.Range(0f, 100f);

        SetupRagdollComponents();
        FindMixamoBones();

        if (headBone != null)
        {
            currentHeadRotation = headBone.rotation;
        }

        if (player == null)
        {
            GameObject playerObj = GameObject.FindGameObjectWithTag("Player");
            if (playerObj != null)
            {
                player = playerObj.transform;
            }
        }

        // Apply initial ragdoll state (off by default unless checked in Inspector)
        SetRagdollState(activateRagdoll);

        if (!isRagdollActive)
        {
            PlayRandomLoopingSound();
        }
    }

    private void SetupRagdollComponents()
    {
        // Grab all child Rigidbodies and Colliders generated by Unity's Ragdoll Wizard
        ragdollRigidbodies = GetComponentsInChildren<Rigidbody>();
        ragdollColliders = GetComponentsInChildren<Collider>();
    }

    // Runs automatically when you click the checkbox in the Inspector
    private void OnValidate()
    {
        if (Application.isPlaying && ragdollRigidbodies != null)
        {
            SetRagdollState(activateRagdoll);
        }
    }

    [ContextMenu("Trigger Ragdoll Now")]
    public void TriggerRagdoll()
    {
        activateRagdoll = true;
        SetRagdollState(true);
    }

    public void SetRagdollState(bool state)
    {
        isRagdollActive = state;
        activateRagdoll = state;

        // Disable Animator so physics can take over the bones
        if (animator != null)
        {
            animator.enabled = !state;
        }

        // Toggle all child bone Rigidbodies
        if (ragdollRigidbodies != null)
        {
            foreach (Rigidbody rb in ragdollRigidbodies)
            {
                if (rb == mainRigidbody) continue;
                rb.isKinematic = !state;
                rb.detectCollisions = state;
            }
        }

        // Toggle all child bone Colliders
        if (ragdollColliders != null)
        {
            foreach (Collider col in ragdollColliders)
            {
                if (col == mainCollider) continue;
                col.enabled = state;
            }
        }

        // Disable main root capsule collider/rigidbody so it doesn't collide with ragdoll limbs
        if (mainCollider != null)
        {
            mainCollider.enabled = !state;
        }

        if (mainRigidbody != null)
        {
            mainRigidbody.isKinematic = state;
        }

        // Stop laughing audio if enabled
        if (state && stopAudioOnRagdoll && audioSource != null && audioSource.isPlaying)
        {
            audioSource.Stop();
        }
    }

    private void FindMixamoBones()
    {
        Transform[] allChildren = GetComponentsInChildren<Transform>();

        if (headBone == null)
        {
            headBone = FindBoneBySuffix(allChildren, "Head");
        }

        if (laughingParts == null || laughingParts.Count == 0)
        {
            laughingParts = new List<Transform>();

            string[] targetLaughBones = new string[]
            {
                "Spine1",
                "Spine2",
                "LeftShoulder",
                "RightShoulder"
            };

            foreach (string boneSuffix in targetLaughBones)
            {
                Transform foundBone = FindBoneBySuffix(allChildren, boneSuffix);
                if (foundBone != null)
                {
                    laughingParts.Add(foundBone);
                }
            }
        }
    }

    private Transform FindBoneBySuffix(Transform[] bones, string suffix)
    {
        foreach (Transform t in bones)
        {
            if (t.name.EndsWith(":" + suffix) || t.name == suffix)
            {
                return t;
            }
        }
        return null;
    }

    private void PlayRandomLoopingSound()
    {
        if (soundList != null && soundList.Length > 0)
        {
            int randomIndex = Random.Range(0, soundList.Length);
            CustomSound chosenSound = soundList[randomIndex];

            if (chosenSound.clip != null)
            {
                audioSource.spatialBlend = spatialBlend;
                audioSource.minDistance = min3DDistance;
                audioSource.maxDistance = max3DDistance;
                audioSource.rolloffMode = rolloffMode;

                audioSource.clip = chosenSound.clip;
                audioSource.volume = chosenSound.volume;

                audioSource.loop = true;
                audioSource.playOnAwake = false;
                audioSource.Play();
            }
            else
            {
                Debug.LogWarning($"[RecorderGuy] The chosen random sound slot ({randomIndex}) has no AudioClip assigned!");
            }
        }
        else
        {
            Debug.LogWarning($"[RecorderGuy] No sounds assigned in the inspector on {gameObject.name}!");
        }
    }

    void LateUpdate()
    {
        // Stop overriding bone transforms once ragdoll physics takes over
        if (isRagdollActive) return;

        HandleLaughShake();
        HandleHeadLook();
    }

    private void HandleLaughShake()
    {
        if (laughingParts == null || laughingParts.Count == 0) return;

        float time = (Time.time + shakeSeed) * shakeSpeed;

        float waveY = Mathf.Sin(time);
        float waveX = Mathf.Sin(time * 0.5f);
        float waveZ = Mathf.Cos(time * 0.75f);

        for (int i = 0; i < laughingParts.Count; i++)
        {
            Transform part = laughingParts[i];
            if (part == null) continue;

            float partOffset = i * 0.6f;

            Vector3 rotOffset = new Vector3(
                Mathf.Sin(time + partOffset) * shakeRotationAmount.x,
                waveY * shakeRotationAmount.y,
                waveZ * shakeRotationAmount.z
            );

            Vector3 posOffset = new Vector3(
                waveX * shakePositionAmount.x,
                Mathf.Abs(waveY) * shakePositionAmount.y,
                waveZ * shakePositionAmount.z
            );

            part.localRotation *= Quaternion.Euler(rotOffset);
            part.localPosition += posOffset;
        }
    }

    private void HandleHeadLook()
    {
        if (headBone == null) return;

        Quaternion targetRotation = headBone.rotation;

        if (player != null)
        {
            Vector3 targetPos = player.position + playerTargetOffset;
            float distance = Vector3.Distance(transform.position, player.position);

            if (distance <= lookDistance)
            {
                Vector3 directionToPlayer = (targetPos - headBone.position).normalized;
                float angleToPlayer = Vector3.Angle(transform.forward, directionToPlayer);

                if (angleToPlayer <= maxLookAngle)
                {
                    targetRotation = Quaternion.LookRotation(directionToPlayer) * Quaternion.Euler(headRotationOffset);
                }
            }
        }

        currentHeadRotation = Quaternion.Slerp(currentHeadRotation, targetRotation, Time.deltaTime * headTurnSpeed);
        headBone.rotation = currentHeadRotation;
    }

    private void OnDrawGizmosSelected()
    {
        Gizmos.color = Color.yellow;
        Gizmos.DrawWireSphere(transform.position, lookDistance);
    }
}